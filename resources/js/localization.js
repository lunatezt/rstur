function getInitialLocale() {
    const savedLocale = window.localStorage.getItem(STORAGE_KEY)
    return supportedLocales.includes(savedLocale) ? savedLocale : 'en'
}

export const locale = ref(getInitialLocale())
applyDocumentLocale(locale.value)

export function t(key, params = {}) {
    let message = translations[locale.value]?.[key] ?? key
    for (const [name, value] of Object.entries(params)) {
        message = message.replaceAll(`{${name}}`, String(value))
    }
    return message
}

function applyDocumentLocale(value) {
    document.documentElement.lang = value === 'prs' ? 'prs-AF' : 'en'
    document.documentElement.dir = value === 'prs' ? 'rtl' : 'ltr'
}

export function setLocale(value) {
    if (!supportedLocales.includes(value)) {
        throw new Error(`Unsupported locale: ${value}`)
    }

    locale.value = value
    window.localStorage.setItem(STORAGE_KEY, value)
    applyDocumentLocale(value)
}

export function useLocalization() {
    return { locale, setLocale, t }
}
